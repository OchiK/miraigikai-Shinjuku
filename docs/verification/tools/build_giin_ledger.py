def murl(c, s, m):
    return f"{MIN}{c}&schedule_id={s}&minute_id={m}"


def norm(t):
    return re.sub(r"[\s　]+", "", t)


sources = {}  # url -> (sha256, 照合用に空白を除いた本文)

# 会議録（API の body をそのまま sha256、照合はタグを除いた本文）
for council, sched, path in [
    (3193, 3, "m3.json"),
    (3193, 4, "m4.json"),
    (3190, 1, "c3190_1.json"),
    (3190, 2, "c3190_2.json"),
]:
    for m in json.load(open(f"{S}/{path}", encoding="utf-8"))["tenant_minutes"]:
        body = m.get("body") or ""
        text = re.sub(r"<[^>]+>", "", body)
        sources[murl(council, sched, m["minute_id"])] = (
            hashlib.sha256(body.encode()).hexdigest(),
            norm(text),
        )


def file_sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def pdf_text(path):
    plain = subprocess.run(["pdftotext", path, "-"], capture_output=True, text=True).stdout
    layout = subprocess.run(
        ["pdftotext", "-layout", path, "-"], capture_output=True, text=True
    ).stdout
    return norm(plain) + "\n" + norm(layout)


