# 会派別の賛否。列の並びは RES の見出し「自参ク 公明 共産 新宿会 民無ク 維新 現役 れいわ」。
VOTE_PATTERN = "×　×　○　×　×　×　×　○"


def vote_fact(overview_tail):
    """RES の採決結果行。概要の末尾から会派の賛否と議決結果まで続けて引く。"""
    return ("RES", "議員提出議案の採決結果行", f"{overview_tail}{VOTE_PATTERN}否決")


def T(field, fact, e, n, h):
    return (field, fact, e, n, h)


def bill(num, prefix, facts, sections):
    for k in list(facts):
        if k in STATUS_KEYS:
            src, sec, exc = facts[k]
            facts[k] = (src, f"審議状況（{sec}）", exc)
    return {
        "slug": f"shinjuku-2026-r1-giin-{num}",
        "prefix": prefix,
        "main": "RES",
        "facts": facts,
        "sections": sections,
    }


def unknown(*claims):
    """出典に記載がない事項の行（fact なし）。claims は (easy, normal, hard)。"""
    return [("content", None, e, n, h) for (e, n, h) in claims]


