/**
 * 会議録検索システムの該当発言へのURL（システムの「URL表示」と同じ形式）
 */
export function buildMinuteUrl(
  session: MinutesSessionKey,
  scheduleId: number,
  minuteId: number
): string {
  const councilId = MINUTES_COUNCIL_IDS[session];
  return `${MINUTES_SEARCH_URL}MinuteView.html?council_id=${councilId}&schedule_id=${scheduleId}&minute_id=${minuteId}`;
}

/** 氏名の突合用。名簿は「木もと ひろゆき」、会議録は「木もとひろゆき」 */
export function normalizeMemberName(name: string): string {
  return name.replace(/\s/g, "");
}

